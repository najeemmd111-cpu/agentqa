"""Execution engines.

* HttpxEngine  : runs scenarios in-process (fast; also supports an ASGI app for tests).
* PytestEngine : renders the scenarios into a real pytest suite (`test_agentqa_generated.py`),
                 runs it with pytest, and reads back detailed results. The generated file
                 can be committed to a repo and re-run in CI without the agent.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

import httpx

from .models import Result, Scenario
from .runtime import run_scenario


class HttpxEngine:
    """Runs scenarios with httpx. Pass `client` to reuse an existing client (e.g. Starlette's
    TestClient for an in-process app); otherwise one is created for `base_url`."""

    def __init__(self, base_url: str, auth_header: str | None = None, client: httpx.Client | None = None, timeout: float = 15.0):
        self.base_url = base_url
        self.auth_header = auth_header
        self.client = client
        self.timeout = timeout

    def run(self, scenarios: list[Scenario]) -> list[Result]:
        if self.client is not None:
            return [run_scenario(self.client, s, self.auth_header) for s in scenarios]
        with httpx.Client(base_url=self.base_url, timeout=self.timeout) as client:
            return [run_scenario(client, s, self.auth_header) for s in scenarios]


PYTEST_TEMPLATE = '''"""Generated by AgentQA. Re-run with:  AGENTQA_BASE_URL=http://localhost:8000 pytest {filename}"""
import json
import os
from pathlib import Path

import httpx
import pytest

from agentqa.agent.models import Scenario
from agentqa.agent.runtime import run_scenario

SCENARIOS = [Scenario.model_validate(s) for s in json.loads(Path(__file__).with_suffix(".json").read_text())]
BASE_URL = os.environ.get("AGENTQA_BASE_URL", {base_url!r})
AUTH = os.environ.get("AGENTQA_AUTH", {auth!r}) or None
RESULTS = os.environ.get("AGENTQA_RESULTS")


@pytest.fixture(scope="session")
def client():
    with httpx.Client(base_url=BASE_URL, timeout=15) as c:
        yield c


@pytest.mark.parametrize("scenario", SCENARIOS, ids=[s.id for s in SCENARIOS])
def test_scenario(client, scenario):
    result = run_scenario(client, scenario, AUTH)
    if RESULTS:
        with open(RESULTS, "a", encoding="utf-8") as fh:
            fh.write(result.model_dump_json() + "\\n")
    assert result.passed, f"{{scenario.name}}: {{result.failure_reason}} | {{result.response_excerpt}}"
'''


def export_pytest(scenarios: list[Scenario], out_dir: Path, base_url: str, auth_header: str | None) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    test_file = out_dir / "test_agentqa_generated.py"
    test_file.with_suffix(".json").write_text(json.dumps([s.model_dump(mode="json") for s in scenarios], indent=2), encoding="utf-8")
    test_file.write_text(PYTEST_TEMPLATE.format(filename=test_file.name, base_url=base_url, auth=auth_header or ""), encoding="utf-8")
    return test_file


class PytestEngine:
    def __init__(self, base_url: str, auth_header: str | None = None, out_dir: Path | None = None):
        self.base_url = base_url
        self.auth_header = auth_header
        self.out_dir = out_dir

    def run(self, scenarios: list[Scenario]) -> list[Result]:
        out_dir = self.out_dir or Path(tempfile.mkdtemp(prefix="agentqa-"))
        test_file = export_pytest(scenarios, out_dir, self.base_url, self.auth_header)
        results_file = out_dir / "results.jsonl"
        results_file.unlink(missing_ok=True)
        env = {
            **os.environ,
            "AGENTQA_BASE_URL": self.base_url,
            "AGENTQA_AUTH": self.auth_header or "",
            "AGENTQA_RESULTS": str(results_file),
            "PYTHONPATH": os.pathsep.join([str(Path(__file__).resolve().parents[2]), os.environ.get("PYTHONPATH", "")]),
        }
        subprocess.run(
            [sys.executable, "-m", "pytest", str(test_file), "-q", "-p", "no:cacheprovider", f"--junitxml={out_dir / 'junit.xml'}"],
            env=env,
            capture_output=True,
            text=True,
            cwd=out_dir,
        )
        if not results_file.exists():
            raise RuntimeError("pytest produced no results; check the generated suite in " + str(out_dir))
        by_id = {}
        for line in results_file.read_text(encoding="utf-8").splitlines():
            r = Result.model_validate_json(line)
            by_id[r.scenario.id] = r
        return [by_id[s.id] for s in scenarios if s.id in by_id]
